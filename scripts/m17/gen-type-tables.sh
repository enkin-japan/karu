#!/bin/bash
# M17 T17.10 — built-in type tables (plan §8.2 "T17.10 接口").
#
# Fetches the pinned sources (if missing), verifies them, then generates
#   assets/typetables/python-stdlib.ktt   (typeshed stdlib/, Python 3.13, darwin)
#   assets/typetables/typescript-lib.ktt  (TypeScript lib.es* + lib.dom*)
#   assets/typetables/SOURCES.txt         (pinned versions and hashes)
# Output is deterministic: running twice yields byte-identical files.
#
# Sources live outside the repo (override with KARU_TYPE_SOURCES):
#   /Volumes/enkin/project-support/KaruM17-TypeSources/
# Uses the machine's python3 (3.13; stdlib `ast` must parse the stubs) and node;
# no global installs, no `npm install` (the typescript package has no runtime
# dependencies — its tarball is fetched and unpacked directly).
#
# Usage: bash scripts/m17/gen-type-tables.sh [--check]
#   --check  regenerate into a temporary directory and `cmp` against assets/
set -euo pipefail
cd "$(dirname "$0")/../.."
ROOT="$(pwd)"

# --- pinned sources ---------------------------------------------------------
TYPESHED_REPO="https://github.com/python/typeshed"
TYPESHED_COMMIT="983d92a71d4345d4272f2d022745efc434990674"
# typescript 7.x is the native (Go) compiler without the JS compiler API; 6.0.3
# is the latest release that ships `lib/typescript.js` and the lib .d.ts files.
TS_VERSION="6.0.3"
TS_TARBALL="https://registry.npmjs.org/typescript/-/typescript-${TS_VERSION}.tgz"
TS_INTEGRITY="sha512-y2TvuxSZPDyQakkFRPZHKFm+KKVqIisdg9/CZwm9ftvKXLP8NRWj38/ODjNbr43SsoXqNuAisEf1GdCxqWcdBw=="
TS_SHASUM="90251dc007916e972786cb94d74d15b185577d21"

SRC="${KARU_TYPE_SOURCES:-/Volumes/enkin/project-support/KaruM17-TypeSources}"
TYPESHED_DIR="$SRC/typeshed-${TYPESHED_COMMIT:0:12}"
TS_DIR="$SRC/typescript-${TS_VERSION}"
TS_TGZ="$SRC/typescript-${TS_VERSION}.tgz"

python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 13) else 1)' \
    || { echo "ERROR: python3 >= 3.13 required" >&2; exit 1; }
command -v node >/dev/null || { echo "ERROR: node required" >&2; exit 1; }
mkdir -p "$SRC"

# --- typeshed: shallow fetch of the pinned commit; git verifies object hashes --
if [ ! -d "$TYPESHED_DIR/.git" ]; then
    echo "fetching typeshed $TYPESHED_COMMIT"
    rm -rf "$TYPESHED_DIR.tmp"
    git init -q "$TYPESHED_DIR.tmp"
    git -C "$TYPESHED_DIR.tmp" fetch -q --depth 1 "$TYPESHED_REPO" "$TYPESHED_COMMIT"
    git -C "$TYPESHED_DIR.tmp" -c advice.detachedHead=false checkout -q FETCH_HEAD
    mv "$TYPESHED_DIR.tmp" "$TYPESHED_DIR"
fi
head_commit="$(git -C "$TYPESHED_DIR" rev-parse HEAD)"
[ "$head_commit" = "$TYPESHED_COMMIT" ] \
    || { echo "ERROR: typeshed HEAD $head_commit != pinned $TYPESHED_COMMIT" >&2; exit 1; }
# Working tree must match the commit exactly (no local edits, no extra files).
if [ -n "$(git -C "$TYPESHED_DIR" status --porcelain --untracked-files=all)" ]; then
    echo "ERROR: typeshed checkout at $TYPESHED_DIR is modified" >&2; exit 1
fi
git -C "$TYPESHED_DIR" fsck --no-dangling --no-progress >/dev/null 2>&1 \
    || { echo "ERROR: typeshed object store failed fsck" >&2; exit 1; }
STDLIB_TREE="$(git -C "$TYPESHED_DIR" rev-parse HEAD:stdlib)"

# --- typescript: registry tarball, verified against the pinned integrity -------
if [ ! -f "$TS_TGZ" ]; then
    echo "fetching typescript $TS_VERSION"
    curl -fsSL "$TS_TARBALL" -o "$TS_TGZ.tmp"
    mv "$TS_TGZ.tmp" "$TS_TGZ"
fi
got_integrity="sha512-$(openssl dgst -sha512 -binary "$TS_TGZ" | openssl base64 -A)"
got_shasum="$(shasum -a 1 "$TS_TGZ" | cut -d' ' -f1)"
if [ "$got_integrity" != "$TS_INTEGRITY" ] || [ "$got_shasum" != "$TS_SHASUM" ]; then
    echo "ERROR: $TS_TGZ does not match the pinned integrity/shasum" >&2; exit 1
fi
# Unpack fresh each run so the inputs are exactly the verified tarball.
rm -rf "$TS_DIR"
mkdir -p "$TS_DIR"
tar -xzf "$TS_TGZ" -C "$TS_DIR"
[ -f "$TS_DIR/package/lib/typescript.js" ] || { echo "ERROR: typescript.js missing" >&2; exit 1; }

# --- generate --------------------------------------------------------------
OUT="$ROOT/assets/typetables"
if [ "${1:-}" = "--check" ]; then
    OUT="$(mktemp -d)"
    trap 'rm -rf "$OUT"' EXIT
fi
mkdir -p "$OUT"

python3 -I "$ROOT/scripts/m17/gen_python_types.py" "$TYPESHED_DIR/stdlib" "$OUT/python-stdlib.ktt"
node "$ROOT/scripts/m17/gen-ts-types.mjs" "$TS_DIR/package" "$OUT/typescript-lib.ktt"

cat > "$OUT/SOURCES.txt" <<EOF
Karu built-in type tables (M17 T17.10). Generated by scripts/m17/gen-type-tables.sh.
Licences: docs/THIRD-PARTY-NOTICES.md.

python-stdlib.ktt
  source:  typeshed ($TYPESHED_REPO), directory stdlib/
  commit:  $TYPESHED_COMMIT
  stdlib tree: $STDLIB_TREE
  evaluated for: sys.version_info = (3, 13), sys.platform = "darwin"
  licence: Apache-2.0 (typeshed LICENSE; some files MIT, see LICENSE)

typescript-lib.ktt
  source:  npm package typescript@$TS_VERSION ($TS_TARBALL)
  integrity: $TS_INTEGRITY
  shasum:  $TS_SHASUM
  files:   lib.es5 ... lib.esnext (+ lib.decorators*), lib.dom, lib.dom.iterable, lib.dom.asynciterable
  licence: Apache-2.0; DOM declarations carry the W3C/WHATWG notice (ThirdPartyNoticeText.txt)
EOF

if [ "${1:-}" = "--check" ]; then
    status=0
    for f in python-stdlib.ktt typescript-lib.ktt SOURCES.txt; do
        if cmp -s "$OUT/$f" "$ROOT/assets/typetables/$f"; then
            echo "identical: $f"
        else
            echo "DIFFERS:   $f"; status=1
        fi
    done
    exit $status
fi
ls -l "$OUT"
